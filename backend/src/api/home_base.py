#!/usr/bin/env python3
"""
Home-base pairing API.

Creates short-lived single-use QR challenges, redeems them to activate a home
base, reports pairing/model status, and lets the owner revoke a paired base.
"""

from fastapi import APIRouter, Depends, HTTPException, Request
from fastapi.responses import HTMLResponse
from pydantic import BaseModel
from sqlalchemy.orm import Session

from api.auth import get_current_user
from db.models import BaseService
from db.session import get_db
from services import home_base as hb
from services.rate_limit import RateLimitedError, limiter

router = APIRouter(prefix="/api/home-base", tags=["Home Base"])


def _user_id(user):
    data = dict(user._asdict()) if hasattr(user, "_asdict") else dict(user)
    return data["id"]


class PairRequest(BaseModel):
    token: str
    name: str | None = None


@router.post("/pairing-challenge")
def create_challenge(db: Session = Depends(get_db), user=Depends(get_current_user)):
    uid = _user_id(user)
    try:
        limiter.check(f"pair-challenge:{uid}", limit=5, window_seconds=300)
    except RateLimitedError as exc:
        raise HTTPException(status_code=429, detail={"code": "RATE_LIMITED", "message": str(exc)})
    service = BaseService(db)
    challenge = hb.create_pairing_challenge(service, uid)
    # The plaintext token is returned only here (it is what the QR encodes).
    return challenge


@router.post("/pair")
def pair_device(payload: PairRequest, db: Session = Depends(get_db), user=Depends(get_current_user)):
    """Redeem a challenge generated by the authenticated user's phone."""
    uid = _user_id(user)
    service = BaseService(db)
    try:
        home_base = hb.redeem_pairing(service, payload.token, payload.name)
    except ValueError as exc:
        raise HTTPException(status_code=400, detail={"code": "PAIRING_INVALID", "message": str(exc)})
    if home_base["id"] is None:
        raise HTTPException(status_code=400, detail={"code": "PAIRING_INVALID", "message": "Pairing failed."})
    return {"home_base": home_base}


@router.get("/status")
def get_status(db: Session = Depends(get_db), user=Depends(get_current_user)):
    uid = _user_id(user)
    service = BaseService(db)
    return hb.get_status(service, uid)


@router.post("/{home_base_id}/revoke")
def revoke(home_base_id: int, db: Session = Depends(get_db), user=Depends(get_current_user)):
    uid = _user_id(user)
    service = BaseService(db)
    try:
        hb.revoke_home_base(service, uid, home_base_id)
    except ValueError as exc:
        raise HTTPException(status_code=404, detail={"code": "HOME_BASE_NOT_FOUND", "message": str(exc)})
    return {"message": "Home base revoked."}


